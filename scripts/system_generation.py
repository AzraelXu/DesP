#!/usr/bin/env python3
"""Helpers for batch per-system config generation.

Used by scripts/generate_systems.py. The CLI and orchestration live there;
this module contains discovery, structure inspection orchestration, ligand
detection, naming, rendering, and file I/O helpers.
"""

import json
import os
import re
import string
import subprocess
import sys
import tempfile
from collections import defaultdict

EXTENSIONS = {".pdb", ".mae", ".maegz"}
PREPARED_EXTENSIONS = {".mae", ".maegz"}
GENERATED_MARKER = "Batch-generated by desmond_md_pipeline"
GENERIC_RESNAMES = {"UNK", "UNL", "LIG", "MOL", "XXX", "DUM"}
CHAIN_RE = re.compile(r"^[A-Za-z0-9_.-]+$")
RESNAME_RE = re.compile(r"^[A-Za-z0-9_.+-]+$")
PLACEHOLDER_FIELDS = ("stem", "target", "ligand", "index")
LIGAND_NAME_SOURCES = ("filename", "resname", "index")
SKIP_DIR_NAMES = {"projects", "results", "systems", ".gpu_locks", "__pycache__", ".git"}


class GenerationError(Exception):
    """A per-system or global error with a user-facing message."""


def warn(message):
    print("[WARN] {}".format(message))


def fatal(message):
    print("FATAL: {}".format(message), file=sys.stderr)


def template_fields(template):
    """Return the placeholder names used by a format template."""
    fields = set()
    for _literal, field_name, _spec, _conv in string.Formatter().parse(template):
        if field_name is None:
            continue
        if not field_name or "." in field_name or "[" in field_name:
            raise ValueError("unsupported placeholder {!r}".format(field_name))
        fields.add(field_name)
    return fields


def resolve_schrodinger():
    value = os.environ.get("SCHRODINGER", "").strip()
    if not value:
        raise GenerationError("SCHRODINGER is not set; run through scripts/generate_systems.sh")
    run_exe = os.path.join(value, "run")
    if not os.path.isfile(run_exe) or not os.access(run_exe, os.X_OK):
        raise GenerationError("Schrodinger not found: {}".format(value))
    return run_exe


def resolve_systems_dir():
    root = os.environ.get("SCH_WORK_ROOT", "").strip()
    if not root:
        raise GenerationError("SCH_WORK_ROOT is not set; run init_user.sh first")
    systems_dir = os.path.join(root, "systems")
    if not os.path.isdir(systems_dir):
        raise GenerationError(
            "systems directory not found: {}; run init_user.sh first".format(systems_dir))
    return systems_dir


def entry_for(path, display, index):
    real_path = os.path.realpath(path)
    stem, ext = os.path.splitext(os.path.basename(path))
    try:
        display.encode("utf-8")
    except UnicodeEncodeError:
        display = display.encode("utf-8", "backslashreplace").decode("ascii")
    error = None
    try:
        path.encode("utf-8")
        real_path.encode("utf-8")
    except UnicodeEncodeError:
        error = "path is not valid UTF-8"
    if error is None:
        if ext.lower() not in EXTENSIONS:
            error = "unsupported structure extension {!r}; expected .pdb, .mae, or .maegz".format(ext)
        elif not os.path.isfile(real_path):
            error = "file not found or not a regular file"
    return {
        "path": real_path,
        "display": display,
        "index": index,
        "stem": stem,
        "ext": ext.lower(),
        "error": error,
    }


def discover_structures(args):
    entries = []
    if args.manifest:
        base = os.path.dirname(os.path.abspath(args.manifest))
        try:
            with open(args.manifest, "r", encoding="utf-8") as handle:
                for line in handle:
                    text = line.strip()
                    if not text or text.startswith("#"):
                        continue
                    path = os.path.expanduser(text)
                    if not os.path.isabs(path):
                        path = os.path.join(base, path)
                    entries.append(entry_for(os.path.abspath(path), text, len(entries) + 1))
        except UnicodeDecodeError as exc:
            raise GenerationError("--manifest is not valid UTF-8: {}".format(exc))
        except OSError as exc:
            raise GenerationError("cannot read --manifest {}: {}".format(args.manifest, exc))
        return entries

    try:
        root = os.path.abspath(args.input_dir)
    except OSError as exc:
        raise GenerationError("cannot resolve input directory: {}".format(exc))
    paths = []
    if args.recursive:
        for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
            keep = []
            for dirname in dirnames:
                full = os.path.join(dirpath, dirname)
                if dirname.startswith(".") or dirname in SKIP_DIR_NAMES:
                    continue
                if os.path.islink(full):
                    continue
                if os.path.isfile(os.path.join(full, ".desmond_work_root")):
                    continue
                keep.append(dirname)
            dirnames[:] = keep
            for filename in filenames:
                path = os.path.join(dirpath, filename)
                if os.path.splitext(filename)[1].lower() in EXTENSIONS and os.path.isfile(path):
                    paths.append(path)
    else:
        try:
            names = os.listdir(root)
        except OSError as exc:
            raise GenerationError("cannot read input directory {}: {}".format(root, exc))
        for filename in names:
            path = os.path.join(root, filename)
            if os.path.splitext(filename)[1].lower() in EXTENSIONS and os.path.isfile(path):
                paths.append(path)

    def sort_key(path):
        stem = os.path.splitext(os.path.basename(path))[0]
        return (stem.casefold(), stem, path)

    paths.sort(key=sort_key)
    seen = set()
    for path in paths:
        real = os.path.realpath(path)
        if real in seen:
            continue
        seen.add(real)
        entries.append(entry_for(path, os.path.relpath(path, root), len(entries) + 1))
    return entries


def run_inspector(run_exe, inspector, path, tmpdir, ligand_asl=None, check_asls=None):
    try:
        fd, json_path = tempfile.mkstemp(dir=tmpdir, prefix="report_", suffix=".json")
        os.close(fd)
    except OSError as exc:
        raise GenerationError("cannot create inspector report: {}".format(exc))
    cmd = [run_exe, "python3", inspector, "--structure", path, "--json-out", json_path]
    if check_asls is not None:
        receptor_asl, ligand_selection, align_asl = check_asls
        cmd += ["--receptor-asl", receptor_asl, "--ligand-asl", ligand_selection,
                "--align-asl", align_asl, "--check"]
    elif ligand_asl:
        cmd += ["--ligand-asl", ligand_asl]
    try:
        try:
            proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                  universal_newlines=True)
        except OSError as exc:
            raise GenerationError("cannot run structure inspector: {}".format(exc))
        if proc.returncode != 0:
            detail = (proc.stderr or proc.stdout or "").strip()
            if len(detail) > 600:
                detail = "..." + detail[-600:]
            raise GenerationError("structure inspection failed (exit {}): {}".format(
                proc.returncode, detail or "no output"))
        try:
            with open(json_path, "r", encoding="utf-8") as handle:
                return json.load(handle)
        except (OSError, ValueError) as exc:
            raise GenerationError("cannot read inspector report: {}".format(exc))
    finally:
        try:
            os.unlink(json_path)
        except OSError:
            pass


def validate_chain(chain, display):
    if chain == "<blank>":
        raise GenerationError(
            "{}: blank chain IDs; assign chain IDs or use --ligand-asl".format(display))
    if not CHAIN_RE.match(chain):
        raise GenerationError(
            "{}: chain ID {!r} contains characters unsafe for ASL; "
            "assign a simple chain ID or use --ligand-asl".format(display, chain))


def single_resname(hetero_groups, chains):
    groups = [g for g in hetero_groups if str(g.get("chain", "")).strip() in chains]
    if len(groups) == 1:
        return str(groups[0].get("resname", "")).strip() or None
    return None


def detect_ligand(report, args, display):
    chains = report.get("chains") or {}
    hetero_groups = report.get("hetero_groups") or []
    by_chain = defaultdict(list)
    for group in hetero_groups:
        chain = str(group.get("chain", "")).strip()
        by_chain[chain].append(group)

    if args.ligand_asl:
        asl_info = (report.get("asl") or {}).get("ligand") or {}
        if asl_info.get("error"):
            raise GenerationError(
                "{}: ligand ASL failed: {}".format(display, asl_info["error"]))
        if "chains" not in asl_info:
            raise GenerationError(
                "{}: inspector report has no ASL chain information; "
                "update scripts/inspect_structure.py".format(display))
        selected = [str(c).strip() for c in asl_info.get("chains") or []]
        if not selected or not asl_info.get("atoms"):
            raise GenerationError(
                "{}: ligand ASL selected 0 atoms: {!r}".format(display, args.ligand_asl))
        selected_set = set(selected)
        if args.ligand_chain and selected_set != {args.ligand_chain}:
            raise GenerationError(
                "{}: ligand ASL selects chain(s) {} but --ligand-chain is {}".format(
                    display, ",".join(sorted(selected_set)), args.ligand_chain))
        return {
            "chains": selected_set,
            "ligand_asl": args.ligand_asl,
            "expected_atoms": None,
            "resname": single_resname(hetero_groups, selected_set),
            "warnings": [],
        }

    if args.ligand_resnames:
        wanted = {name.upper() for name in args.ligand_resnames}
        matches = [g for g in hetero_groups
                   if str(g.get("resname", "")).strip().upper() in wanted]
        if args.ligand_chain:
            matches = [g for g in matches
                       if str(g.get("chain", "")).strip() == args.ligand_chain]
            if not matches:
                raise GenerationError(
                    "{}: no non-polymer group on chain {} matched --ligand-resname {}".format(
                        display, args.ligand_chain, ",".join(args.ligand_resnames)))
        if not matches:
            raise GenerationError(
                "{}: no non-polymer group matched --ligand-resname {}".format(
                    display, ",".join(args.ligand_resnames)))
        matched_chains = {str(g.get("chain", "")).strip() for g in matches}
        if len(matched_chains) != 1:
            raise GenerationError(
                "{}: --ligand-resname matches multiple chains: {}".format(
                    display, ",".join(sorted(matched_chains))))
        chain = matched_chains.pop()
        validate_chain(chain, display)
        if len(matches) != 1:
            raise GenerationError(
                "{}: --ligand-resname matches {} groups; pass --ligand-asl".format(
                    display, len(matches)))
        group = matches[0]
        resname = str(group.get("resname", "")).strip()
        if not RESNAME_RE.match(resname):
            raise GenerationError(
                "{}: residue name {!r} cannot be used in an ASL; pass --ligand-asl".format(
                    display, resname))
        warnings = []
        if int((chains.get(chain) or {}).get("polymer_residues", 0)) > 0:
            warnings.append(
                "chain {} has both polymer and non-polymer groups; verify LIGAND_ASL".format(chain))
        return {
            "chains": {chain},
            "ligand_asl": "chain {} and res.ptype {}".format(chain, resname),
            "expected_atoms": int(group.get("atoms", 0)),
            "resname": resname,
            "warnings": warnings,
        }

    if args.ligand_chain:
        chain = args.ligand_chain
        if chain not in chains:
            raise GenerationError(
                "{}: --ligand-chain {} not found (available chains: {})".format(
                    display, chain, ", ".join(sorted(chains)) or "(none)"))
        validate_chain(chain, display)
        groups = by_chain.get(chain, [])
        if len(groups) > 1:
            detail = ", ".join("{}:{} ({} atoms)".format(
                g.get("resname"), g.get("resnum"), g.get("atoms")) for g in groups)
            raise GenerationError(
                "{}: chain {} contains multiple non-polymer groups: {}; "
                "pass --ligand-resname or --ligand-asl".format(display, chain, detail))
        warnings = []
        resname = None
        expected_atoms = None
        if not groups:
            polymer_residues = int((chains.get(chain) or {}).get("polymer_residues", 0))
            if polymer_residues > 0:
                warnings.append(
                    "chain {} looks like a polymer/peptide ligand; verify LIGAND_ASL".format(chain))
            else:
                raise GenerationError(
                    "{}: chain {} has no non-polymer ligand group".format(display, chain))
        else:
            resname = str(groups[0].get("resname", "")).strip() or None
            expected_atoms = int(groups[0].get("atoms", 0))
        return {
            "chains": {chain},
            "ligand_asl": "chain {}".format(chain),
            "expected_atoms": expected_atoms,
            "resname": resname,
            "warnings": warnings,
        }

    candidates = {chain: groups for chain, groups in by_chain.items() if groups}
    if not candidates:
        raise GenerationError(
            "{}: no non-polymer ligand group detected; pass --ligand-chain or --ligand-asl "
            "(peptide ligands are not auto-detected)".format(display))
    if len(candidates) > 1:
        detail = "; ".join(
            "{} ({})".format(chain, ",".join(sorted({str(g.get("resname", "")) for g in groups})))
            for chain, groups in sorted(candidates.items()))
        raise GenerationError(
            "{}: multiple candidate ligand chains: {}; pass --ligand-chain or "
            "--ligand-resname".format(display, detail))
    chain, groups = next(iter(candidates.items()))
    validate_chain(chain, display)
    if len(groups) > 1:
        detail = ", ".join("{} ({})".format(g.get("resname"), g.get("atoms")) for g in groups)
        raise GenerationError(
            "{}: multiple ligand residues on chain {}: {}; pass --ligand-resname or "
            "--ligand-asl".format(display, chain, detail))
    group = groups[0]
    warnings = []
    if int((chains.get(chain) or {}).get("polymer_residues", 0)) > 0:
        warnings.append(
            "chain {} has both polymer and non-polymer groups; verify LIGAND_ASL".format(chain))
    return {
        "chains": {chain},
        "ligand_asl": "chain {}".format(chain),
        "expected_atoms": int(group.get("atoms", 0)),
        "resname": str(group.get("resname", "")).strip() or None,
        "warnings": warnings,
    }


def build_receptor_asl(report, ligand_info, display):
    chains = report.get("chains") or {}
    ligand_chains = set(ligand_info["chains"])
    polymer_chains = {
        chain for chain, info in chains.items()
        if int(info.get("polymer_residues", 0)) > 0
    }
    entirely_ligand = ligand_chains - polymer_chains
    receptor_chains = polymer_chains - entirely_ligand
    if not receptor_chains:
        raise GenerationError(
            "{}: not a protein-ligand complex: no polymer chains remain after "
            "excluding the ligand chain".format(display))
    invalid = [chain for chain in receptor_chains
               if chain == "<blank>" or not CHAIN_RE.match(chain)]
    if invalid:
        base = "protein"
    else:
        ordered = sorted(receptor_chains)
        if len(ordered) == 1:
            base = "chain {}".format(ordered[0])
        else:
            base = " or ".join("chain {}".format(chain) for chain in ordered)
    if receptor_chains & ligand_chains:
        return "({}) and not ({})".format(base, ligand_info["ligand_asl"])
    return base


def validate_asls(run_exe, inspector, entry, receptor_asl, ligand_info, tmpdir):
    align_asl = "({}) and backbone and not (atom.ele H)".format(receptor_asl)
    report = run_inspector(
        run_exe, inspector, entry["path"], tmpdir,
        check_asls=(receptor_asl, ligand_info["ligand_asl"], align_asl))
    ligand_asl = (report.get("asl") or {}).get("ligand") or {}
    atoms = ligand_asl.get("atoms")
    expected = ligand_info.get("expected_atoms")
    if expected is not None and atoms != expected:
        raise GenerationError(
            "{}: ligand ASL selected {} atoms but the ligand residue has {}; "
            "pass --ligand-asl to select it explicitly".format(
                entry["display"], atoms if atoms is not None else "?", expected))
    return report


def derive_ligand_name(entry, ligand_info, args):
    stem = entry["stem"]
    for source in args.ligand_name_sources:
        if source == "filename":
            if args.ligand_re is not None:
                match = args.ligand_re.search(stem)
                if not match:
                    continue
                if "ligand" in args.ligand_re.groupindex and match.group("ligand") is not None:
                    value = match.group("ligand")
                elif args.ligand_re.groups >= 1 and match.group(1) is not None:
                    value = match.group(1)
                else:
                    continue
                value = value.strip()
                if value:
                    return value
                continue
            if args.target:
                prefix = args.target
                if (len(stem) > len(prefix)
                        and stem[:len(prefix)].lower() == prefix.lower()
                        and stem[len(prefix)] in "_-."):
                    remainder = stem[len(prefix) + 1:].strip()
                    if remainder:
                        return remainder
            return stem
        if source == "resname":
            resname = ligand_info.get("resname")
            if resname and resname.upper() not in GENERIC_RESNAMES:
                return resname
            continue
        if source == "index":
            return str(entry["index"])
    raise GenerationError(
        "cannot derive a ligand name for {} from --ligand-name-source {}".format(
            entry["display"], ",".join(args.ligand_name_sources)))


def normalize_system_name(raw):
    name = re.sub(r"[^A-Za-z0-9_.-]+", "_", raw.strip())
    name = re.sub(r"_+", "_", name).strip("_.")
    if not name:
        name = "system"
    if not re.match(r"[A-Za-z0-9]", name[0]):
        name = "s" + name
    return name


def system_name_for(entry, ligand_info, args):
    values = {"stem": entry["stem"], "index": entry["index"]}
    used_fields = getattr(args, "name_template_fields", {"ligand"})
    if "ligand" in used_fields:
        values["ligand"] = derive_ligand_name(entry, ligand_info, args)
    if args.target:
        values["target"] = args.target
    try:
        raw = args.name_template.format_map(values)
    except (KeyError, IndexError, ValueError) as exc:
        raise GenerationError(
            "cannot format --name-template for {}: {}".format(entry["display"], exc))
    return normalize_system_name(raw)


def bash_quote(value):
    if "\n" in value or "\r" in value:
        raise GenerationError("value contains a newline: {!r}".format(value))
    escaped = (value.replace("\\", "\\\\")
                    .replace('"', '\\"')
                    .replace("$", "\\$")
                    .replace("`", "\\`"))
    return '"{}"'.format(escaped)


def render_config(entry, system_name, args, receptor_asl, ligand_info):
    path = entry["path"]
    if "\n" in path or "\r" in path:
        raise GenerationError("{}: structure path contains a newline".format(entry["display"]))
    lines = [
        "# =============================================================================",
        "# {} scripts/generate_systems.py.".format(GENERATED_MARKER),
        "# Source: {}".format(path),
        "# Re-run scripts/generate_systems.sh --overwrite to refresh this file.",
        "# =============================================================================",
        "",
        "SYSTEM_NAME={}".format(bash_quote(system_name)),
        "",
    ]
    if args.structure_field == "prepared":
        if entry["ext"] not in PREPARED_EXTENSIONS:
            raise GenerationError(
                "{}: --structure-field prepared requires .mae or .maegz".format(
                    entry["display"]))
        lines += [
            "# Already prepared complex (MAE/maegz): PrepWizard is skipped.",
            "PREPARED_STRUCTURE={}".format(bash_quote(path)),
        ]
    else:
        lines += [
            "# Raw protein-ligand complex: PrepWizard runs before system building.",
            "INPUT_STRUCTURE={}".format(bash_quote(path)),
        ]
    lines += [
        "",
        "RECEPTOR_ASL={}".format(bash_quote(receptor_asl)),
        "LIGAND_ASL={}".format(bash_quote(ligand_info["ligand_asl"])),
        "",
    ]
    content = "\n".join(lines)
    try:
        content.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise GenerationError(
            "{}: generated config is not valid UTF-8: {}".format(entry["display"], exc))
    return content


def bash_syntax_check(content, display):
    try:
        proc = subprocess.run(["bash", "-n"], input=content, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, universal_newlines=True)
    except OSError as exc:
        raise GenerationError("{}: cannot run bash -n: {}".format(display, exc))
    if proc.returncode != 0:
        raise GenerationError(
            "{}: generated config is not valid Bash: {}".format(
                display, (proc.stderr or "").strip()))


def existing_action(path, content, policy):
    if not os.path.lexists(path):
        return "create", None
    if os.path.islink(path) or not os.path.isfile(path):
        return "fail", "existing path is not a regular file; refusing to overwrite"
    try:
        with open(path, "rb") as handle:
            current = handle.read()
    except OSError as exc:
        return "fail", "cannot read existing config: {}".format(exc)
    if current == content.encode("utf-8"):
        return "skip_unchanged", None
    if policy == "skip":
        return "skip_differs", None
    if policy == "overwrite":
        return "overwrite", None
    return "fail", "config exists and differs"


def write_config(path, content):
    directory = os.path.dirname(path)
    fd, tmp_path = tempfile.mkstemp(dir=directory, prefix=".tmp.", suffix=".conf")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(tmp_path, 0o644)
        os.replace(tmp_path, path)
        tmp_path = None
    finally:
        if tmp_path is not None:
            try:
                os.unlink(tmp_path)
            except OSError:
                pass


def resolve_names(successes, args):
    by_name = defaultdict(list)
    for item in successes:
        by_name[item["system_name"]].append(item)
    collisions = {name: items for name, items in by_name.items() if len(items) > 1}
    if collisions:
        if args.name_conflict == "error":
            lines = ["system name collision after normalization:"]
            for name, items in sorted(collisions.items()):
                lines.append("  {}: {}".format(
                    name, ", ".join(i["entry"]["display"] for i in items)))
            lines.append("Use --name-conflict suffix or --name-template to disambiguate.")
            raise GenerationError("\n".join(lines))
        reserved = set(by_name)
        used = set()
        for item in successes:
            name = item["system_name"]
            if name not in used:
                used.add(name)
                continue
            suffix = 2
            candidate = "{}_{}".format(name, suffix)
            while candidate in reserved or candidate in used:
                suffix += 1
                candidate = "{}_{}".format(name, suffix)
            item["system_name"] = candidate
            used.add(candidate)

    by_case = defaultdict(list)
    for item in successes:
        by_case[item["system_name"].casefold()].append(item["system_name"])
    for _folded, names in sorted(by_case.items()):
        distinct = sorted(set(names))
        if len(distinct) > 1:
            warn("system names differ only by case: {}".format(", ".join(distinct)))
